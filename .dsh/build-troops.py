#!/usr/bin/env python3
"""Write _data/troops.json from the troop tables two calculators publish.

Usage: python3 .dsh/build-troops.py [path/to/research/troops]

The research folder in the project files holds each site's own table, read from the code
its troop calculator page loads: optimizer.json (Kingshot Optimizer) and kingshotguide.json
(Kingshot Guide). A cell is published only where both agree. A cell only one site has, or
where they differ, is named in the tier's `unverified` and left out, so the published table
never rests on one site alone. The Truegold variants of T10 and T11 train in the same time
for the same cost as the plain tier, so only tiers 1 to 11 are kept."""
import json, sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else '/mnt/project-files/research/troops')
OUT = Path(__file__).resolve().parent.parent / '_data' / 'troops.json'
TYPES = [('inf', 'Infantry', 'barracks', 'infantry', 'infantry', 'infantry'),
         ('cav', 'Cavalry', 'stable', 'cavalry', 'cavalry', 'cavalry'),
         ('arc', 'Archer', 'range', 'archer', 'archery', 'archer')]
RESOURCES = ['bread', 'wood', 'stone', 'iron']
POINTS = ['kvk', 'sg']

optimizer = json.loads((ROOT / 'optimizer.json').read_text())
guide = json.loads((ROOT / 'kingshotguide.json').read_text())
plain = {row['level']: row for row in optimizer['tiers'] if row['tierGroup'] == 'regular' or row['id'] == 'T11'}

tiers = []
for tier in range(1, 12):
    a, key, unverified = plain[tier], 't%d' % tier, []

    def agree(name, x, y):
        if x == y:
            return x
        unverified.append(name)
        return None

    row = {'tier': tier, 'seconds': agree('seconds', a['trainingTimeSeconds'], guide['trainingTimeSeconds'][key]), 'cost': {}, 'points': {}}
    for type_id, _, _, _, opt_key, guide_key in TYPES:
        cost = {}
        for res in RESOURCES:
            value = agree(type_id + '.' + res, a['costs'][opt_key][res], guide['costs'][guide_key][key][res])
            if value is not None:
                cost[res] = value
        row['cost'][type_id] = cost
    for event in POINTS:
        value = agree('points.' + event, a['eventPoints'][event], guide['points'][event][key])
        if value is not None:
            row['points'][event] = value
    if row['seconds'] is None:
        del row['seconds']
    row['unverified'] = unverified
    tiers.append(row)

out = {
    'checkedAt': '2026-10-17',
    'note': 'Per-troop training time in seconds before training speed, and per-troop cost by troop type, for tiers 1 to 11. A cell is published only where Kingshot Optimizer and Kingshot Guide agree; unverified lists the cells they do not. points holds the per-troop KvK prep and Strongest Governor rates both sites give, for tiers an event rule row does not name. Generated by .dsh/build-troops.py.',
    'sources': {
        'optimizer': {'label': 'Kingshot Optimizer', 'url': 'https://kingshotoptimizer.com/calculators/troops'},
        'kingshotguide': {'label': 'Kingshot Guide', 'url': 'https://www.kingshotguide.org/calculator/troops'},
    },
    'types': [{'id': t[0], 'name': t[1], 'camp': t[2]} for t in TYPES],
    'tiers': tiers,
}
OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n')
print('wrote', OUT, '·', sum(len(t['unverified']) for t in tiers), 'unverified cells:', {t['tier']: t['unverified'] for t in tiers if t['unverified']})
