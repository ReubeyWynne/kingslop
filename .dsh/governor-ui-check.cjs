const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), http = require('node:http');
const { chromium } = require('playwright');
const root = path.resolve('_site'), output = path.resolve('.dsh/governor-preview');
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.png': 'image/png', '.webp': 'image/webp' };
const server = http.createServer((req, res) => {
  let file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://localhost').pathname));
  if (!file.startsWith(root + path.sep) && file !== root) return res.writeHead(403).end();
  if (fs.existsSync(file) && fs.statSync(file).isDirectory()) file = path.join(file, 'index.html');
  if (!fs.existsSync(file)) return res.writeHead(404).end();
  res.setHeader('Content-Type', mime[path.extname(file)] || 'application/octet-stream'); fs.createReadStream(file).pipe(res);
});
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = 'http://127.0.0.1:' + server.address().port, browser = await chromium.launch({ headless: true });
  fs.mkdirSync(output, { recursive: true });
  try {
    for (const width of [320, 390, 1280]) {
      const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' }), page = await context.newPage(), errors = [];
      page.on('pageerror', error => errors.push(error.message));
      const ready = () => page.waitForFunction(() => !document.querySelector('.gov-board').disabled);
      const target = key => page.locator('[data-target="governor-planner.' + key + '"]');
      const tile = id => page.locator('.gov-tile[data-item="' + id + '"]');
      await page.goto(origin + '/governor-gear/?lang=en'); await ready();
      assert.equal(await target('count').textContent(), '0');
      assert.match(await target('status').textContent(), /6 not set/);
      assert.equal(await tile('cav-1').locator('.gov-tile-name').textContent(), 'Hat');
      await page.fill('[data-bind="inventory.satin"]', '20000'); await page.fill('[data-bind="inventory.gilded-threads"]', '200'); await page.fill('[data-bind="inventory.artisans-vision"]', '0');
      await page.click('.gov-quick summary');
      await target('fillGear').selectOption('0'); await page.click('[data-action="governor-planner.fill"][data-kind="gear"]');
      assert.equal(await tile('inf-1').getAttribute('data-state'), 'empty');
      // Edit one piece in the dialog: clear it, then step another up and back.
      await tile('arc-2').click();
      const dialog = target('dialog'), gearLevel = dialog.locator('select[data-level="gear"]');
      assert.ok(await dialog.evaluate(node => node.open));
      assert.equal(await target('editTitle').textContent(), 'Staff · Archer');
      await gearLevel.selectOption('');
      await dialog.locator('[data-action="governor-planner.close"]').click();
      assert.equal(await tile('arc-2').getAttribute('data-state'), 'unset');
      await tile('cav-2').click();
      await dialog.locator('.gov-edit-gear [data-step="1"]').click();
      await page.waitForFunction(() => document.querySelector('.gov-tile[data-item="cav-2"] [data-part="level"]').textContent === 'Green 0★');
      assert.match(await target('editNext').textContent(), /Next: Green 1★/);
      await dialog.locator('.gov-edit-gear [data-step="-1"]').click();
      await dialog.locator('[data-charm-row="2"] [data-step="1"]').click();
      await page.waitForFunction(() => document.querySelector('[data-charm="cav-2-2"]').dataset.state === 'set');
      await dialog.locator('[data-charm-row="2"] select').selectOption('');
      await page.keyboard.press('Escape');
      assert.ok(!(await dialog.evaluate(node => node.open)));
      await page.waitForFunction(() => document.querySelectorAll('.gov-steps li').length > 0);
      const steps = await page.locator('.gov-steps .gov-step-item').allTextContents();
      assert.deepEqual(steps.slice(0, 2), ['Armour · Infantry', 'Trousers · Infantry']);
      assert.ok(!steps.includes('Staff · Archer'));
      assert.match(await page.locator('.gov-steps .gov-step-level').first().textContent(), /not crafted → Green 0★/);
      assert.match(await target('events').textContent(), /Alliance Brawl, day 5: about [\d,]+ points/);
      assert.equal(await page.locator('[data-target="governor-planner.spent"] > div').count(), 3);
      if (width < 800) await page.click('[role="tab"][data-value="plan"]');
      await page.click('[data-action="governor-planner.choose"][data-option="focus"][data-value="cav"]');
      await page.waitForFunction(() => [...document.querySelectorAll('.gov-steps .gov-step-item')].every(n => n.textContent.endsWith('Cavalry')));
      await page.click('[role="tab"][data-value="reach"]');
      assert.equal(await page.locator('[data-target="governor-planner.target"] > div').count(), 3);
      assert.match(await target('targetNote').textContent(), /1 not set/);
      await page.click('[role="tab"][data-value="spend"]');
      await page.click('[role="tab"][data-value="charms"]');
      await page.waitForFunction(() => document.querySelector('[data-target="governor-planner.count"]').textContent === '0');
      assert.match(await target('status').textContent(), /not set/);
      await page.click('[role="tab"][data-value="gear"]');
      if (width < 800) await page.click('[role="tab"][data-value="profile"]');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width, 'no sideways scroll at ' + width);
      await page.screenshot({ path: path.join(output, width + '.png'), fullPage: true });
      await page.reload(); await ready();
      assert.equal(await tile('inf-1').getAttribute('data-state'), 'empty');
      assert.equal(await tile('arc-2').getAttribute('data-state'), 'unset');
      assert.equal(await tile('cav-2').getAttribute('data-state'), 'empty');
      assert.equal(await page.locator('[data-option="focus"][data-value="cav"]').getAttribute('aria-pressed'), 'true');
      assert.equal(await page.locator('[data-bind="inventory.satin"]').inputValue(), '20000');
      const other = await context.newPage(); await other.goto(origin + '/hero-gear/?lang=en');
      await other.locator('#gear-mithril').fill('7');
      await page.click('[data-action="governor-planner.reset"]');
      await page.waitForFunction(() => document.querySelector('.gov-tile[data-item="inf-1"]').dataset.state === 'unset');
      assert.match(await page.locator('[data-target="result-panel.message"]').textContent(), /cleared/);
      assert.equal(await page.evaluate(() => PlayerLedger.shared().balance('mithril').amount), 7);
      assert.deepEqual(errors, []);
      await context.close();
    }
    const context = await browser.newContext({ viewport: { width: 390, height: 900 } }), page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(origin + '/governor-gear/?lang=ar'); await page.waitForFunction(() => !document.querySelector('.gov-board').disabled);
    assert.equal(await page.evaluate(() => document.documentElement.dir), 'rtl');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
    await page.goto(origin + '/?lang=en'); await page.waitForFunction(() => window.BH);
    assert.equal(await page.locator('a.event-card[href="governor-gear/"]').count(), 1);
    assert.deepEqual(errors, []);
    await context.close();
    console.log('Governor gear UI: profile tiles, edit dialog, planning, focus, tabs, persistence, shared bag, reset, RTL and widths pass.');
  } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
