const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { withBrowser } = require('./lib/browser-harness.cjs');
const root = path.resolve(process.env.SITE_ROOT || '_site');
withBrowser({ root }, async ({ browser, origin }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  await context.addInitScript(() => { localStorage.setItem('bh:guide', JSON.stringify({ swipe: { done: true }, rail: { done: true }, door: { done: true } })); window.moduleErrors = []; document.addEventListener('module:error', e => moduleErrors.push(e.detail)); });
  const page = await context.newPage(), errors = [], failures = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (new URL(response.url()).origin === origin && response.status() >= 400) failures.push(response.url()); });
  await page.goto(origin + '/seasonal/halloween-party/?lang=en');
  const fact = (key, index) => page.locator('[data-fact="' + key + '"]' + (index === undefined ? '' : '[data-index="' + index + '"]'));
  const plan = (key, index) => page.locator('[data-plan="' + key + '"]' + (index === undefined ? '' : '[data-index="' + index + '"]'));
  const set = async (node, value) => { await node.fill(String(value)); await node.dispatchEvent('change'); };
  await page.waitForFunction(() => window.Halloween && window.Interactions && document.querySelector('[data-target="seasonal.totals"]').children.length);
  assert.equal(await fact('points').inputValue(), '');
  await set(fact('points'), 10000); await set(fact('candy'), 1000); await set(fact('daysLeft'), 3);
  assert.match(await page.locator('[data-target="seasonal.summary"]').textContent(), /2,500/);
  await set(plan('gems'), 2000);
  assert.match(await page.locator('[data-target="seasonal.totals"]').textContent(), /1,020/);
  await page.locator('[data-action="seasonal.forecast"]').click();
  await page.waitForFunction(() => document.querySelector('[data-target="seasonal.forecast-status"]').textContent.includes('median'));
  assert.match(await page.locator('[data-target="seasonal.forecast-result"]').textContent(), /Kingdom age/);
  await fact('packs', 0).selectOption('1'); await fact('packs', 1).selectOption('0');
  await plan('packs', 1).selectOption('1');
  assert.match(await page.locator('[data-target="seasonal.spend"]').textContent(), /4.99/);
  await page.locator('[data-action="seasonal.forecast"]').click();
  await page.waitForFunction(() => document.querySelector('[data-target="seasonal.forecast-result"]').textContent.includes('Without these additional purchases'));
  await page.evaluate(() => PlayerLedger.shared().setBuilding('town-center', 'TG 1'));
  await page.waitForFunction(() => document.querySelector('[data-fact="townCenter"]').value === '30');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('[data-fact="points"]').value === '10000');
  assert.equal(await fact('candy').inputValue(), '1000'); assert.equal(await plan('gems').inputValue(), '0');
  await set(fact('gatheringCollected'), 2990); await set(plan('gathering'), 3000);
  assert.match(await page.locator('[data-target="seasonal.sources"]').textContent(), /Additional gathering10/);
  const other = await context.newPage(); await other.goto(origin + '/seasonal/halloween-party/?lang=en');
  await other.waitForFunction(() => window.PlayerLedger && window.Interactions);
  await other.evaluate(() => { const store = PlayerLedger.shared(), f = store.seasonal('halloween-2026'); f.candy = 2000; store.setSeasonal('halloween-2026', f); });
  await page.waitForFunction(() => document.querySelector('[data-fact="candy"]').value === '2000');
  const snapshot = await page.evaluate(() => PlayerLedger.shared().exportJSON());
  assert.equal(JSON.parse(snapshot).seasonal['halloween-2026'].candy, 2000);
  const third = await browser.newContext(); const imported = await third.newPage(); await imported.goto(origin + '/seasonal/halloween-party/?lang=en');
  await imported.waitForFunction(() => window.PlayerLedger);
  await imported.evaluate(save => PlayerLedger.shared().importJSON(save), snapshot);
  await imported.waitForFunction(() => document.querySelector('[data-fact="candy"]').value === '2000');
  await third.close();
  await page.goto(origin + '/seasonal/halloween-party/?lang=en#pass-age-449');
  await page.waitForFunction(() => document.querySelector('#pass-age-449').open);
  assert.equal(await page.locator('#pass-rewards').getAttribute('open'), '');
  assert.equal(await page.locator('.deck-card[aria-current="page"]').count(), 1);
  for (const width of [320, 768, 1920]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(origin + '/seasonal/halloween-party/?lang=en');
    await page.waitForFunction(() => document.querySelector('[data-fact="points"]').value === '10000');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'page fits at ' + width);
    const overlaps = await page.evaluate(() => { const controls = [...document.querySelectorAll('.topbar > .brand, .topbar > .ev-switch, .topbar > .topbar-right')].filter(n => n.getBoundingClientRect().width && getComputedStyle(n).display !== 'none'); const rects = controls.map(n => n.getBoundingClientRect()); return rects.some((r, i) => rects.some((s, j) => i !== j && r.left < s.right - 2 && r.right > s.left + 2)); });
    assert.equal(overlaps, false, 'topbar fits at ' + width);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(origin + '/seasonal/halloween-party/?lang=ar');
  await page.waitForFunction(() => document.documentElement.lang === 'ar' && document.querySelector('[data-fact="points"]').value === '10000');
  assert.equal(await fact('candy').inputValue(), '2000');
  assert.equal(await page.locator('main').getAttribute('lang'), 'en');
  await page.goto(origin + '/seasonal/?lang=en');
  assert.equal(await page.locator('a[href="halloween-party/#planner"]').count(), 1);
  const ids = await page.evaluate(() => [...document.querySelectorAll('main [id]')].map(n => n.id)); assert.deepEqual(ids.filter((id, i) => ids.indexOf(id) !== i), []);
  await page.goto(origin + '/seasonal/halloween-party/?lang=en');
  await page.waitForFunction(() => document.querySelector('[data-fact="points"]').value === '10000');
  fs.mkdirSync('.dsh/seasonal-preview', { recursive: true });
  await page.screenshot({ path: '.dsh/seasonal-preview/mobile.png', fullPage: true });
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: '.dsh/seasonal-preview/mobile-top.png' });
  await page.locator('#planner').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '.dsh/seasonal-preview/mobile-planner.png' });
  assert.deepEqual(await page.evaluate(() => window.moduleErrors), []); assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  await other.close(); await context.close();
  console.log('Seasonal mobile layout, worker forecast, progress persistence, cross-tab updates, save transfer, deep links and navigation passed.');
}).catch(error => { console.error(error); process.exitCode = 1; });
